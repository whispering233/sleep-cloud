export const LOT_POOL_SIZE = LOT_SIGNS.length;

/** `sc.lot` 的值形状（键协议见 `docs/design/40-client-storage.md` §3）。 */
export interface StoredLot {
  /** 设备本地时区的 `YYYY-MM-DD`，与今天逐字比较 */
  date: string;
  /** 签库下标 `0…LOT_POOL_SIZE-1` */
  no: number;
}

/** 设备本地时区的日期字符串：一天一次的判定就是它与 `StoredLot.date` 的逐字比较。 */
export function localDateOf(now: Date): string {
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, '0');
  const day = String(now.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

/** 今天那张签：日期不同（跨零点 / 从没求过）或下标越界（签库换过内容）都返回 `null`。 */
export function lotOfDay(stored: StoredLot | undefined, today: string): LotSign | null {
  if (stored === undefined || stored.date !== today) return null;
  return LOT_SIGNS[stored.no] ?? null;
}

/** 抽一支：38 条等概率（不按等级加权，等级只是文字）。`random` 可注入，单测用。 */
export function drawLotNo(random: () => number): number {
  return Math.floor(random() * LOT_POOL_SIZE);
}
